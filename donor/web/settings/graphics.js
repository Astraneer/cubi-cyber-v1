const km = (chunks) => { const k = chunks * 16 / 1000; return k < 10 ? k.toFixed(1) : k.toFixed(0); };
function renderSize(scale) {
  const dpr = Math.min(window.devicePixelRatio || 1, 2) * scale;
  return `${Math.max(64, Math.floor(innerWidth * dpr))}×${Math.max(64, Math.floor(innerHeight * dpr))}`;
}

