#!/usr/bin/env python3
"""Generate only references to imported whitelist sounds, preserving credits."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sounds=root/'donor/web/sounds'
manifest=json.loads((sounds/'manifest.json').read_text())
lines=['// Generated by tools/generate_audio_catalog.py from the pinned donor manifest.']
lines.append("pub const EVENTS: &[(&str,&[&str])] = &[")
for name,files in sorted(manifest.items()):
    lines.append('    ('+json.dumps(name)+', &['+','.join(json.dumps(v) for v in files)+']),')
lines.append('];\npub const FILES: &[(&str,&[u8])] = &[')
for name in sorted(set(sum(manifest.values(),[]))):
    if not (sounds/name).is_file() or not name.endswith('.ogg') or '..' in Path(name).parts:
        raise SystemExit('Unexpected or missing donor sound')
    lines.append('    ('+json.dumps(name)+', include_bytes!('+json.dumps('../../../donor/web/sounds/'+name)+')),')
lines.append('];\n')
(root/'crates/audio/src/default_catalog.rs').write_text('\n'.join(lines))
print('AUDIO_CATALOG_READY events='+str(len(manifest))+' files='+str(len(set(sum(manifest.values(),[])))))
