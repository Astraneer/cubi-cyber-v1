import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {heightReferenceSupport} from './height_reference.mjs';
const cameras=JSON.parse(await readFile('.local/height-oracle/cameras.json','utf8'));
const bounds=Object.freeze([-32,-32,48,48]),viewport=Object.freeze([128,128]);
const measuredFixture={subpixelBits:4,rounding:'nearest-even'};
const support=heightReferenceSupport(cameras[1],viewport,[[.5,.5]],measuredFixture,bounds);
assert.equal(support.mask[75*128+43],2,'The original internal Near hole must remain in the strict domain');
assert.equal(support.mask[62*128+113],1,'External silhouette witness is within the measured 4-bit ambiguity');
assert.equal(support.mask[75*128+125],1);
const finer=heightReferenceSupport(cameras[1],viewport,[[.5,.5]],{subpixelBits:8,rounding:'nearest-even'},bounds);
assert.equal(finer.mask[62*128+113],2,'The domain must tighten with independently measured precision');
assert.equal(finer.mask[75*128+125],2);
assert.equal(finer.mask[75*128+43],2);
const top=heightReferenceSupport(cameras[0],viewport,[[.5,.5]],measuredFixture,bounds);
assert.equal(top.mask[80*128+110],2,'The internal Unknown page is never an external-silhouette exception');
assert.deepEqual(Array.from(support.mask),Array.from(heightReferenceSupport(structuredClone(cameras[1]),viewport,[[.5,.5]],structuredClone(measuredFixture),bounds).mask));
for(const edge of support.report.edges)assert.equal(edge.maximumSnapErrorPixels,(Math.abs(edge.inwardNormal[0])+Math.abs(edge.inwardNormal[1]))/32);
assert.equal(support.report.certified+support.report.ambiguous+support.report.outside,128*128);
console.log('HEIGHT_REFERENCE_CPU_OK '+JSON.stringify({certified:support.report.certified,ambiguous:support.report.ambiguous,outside:support.report.outside,fingerprint:support.report.fingerprint,edgeBounds:support.report.edges.map(edge=>edge.maximumSnapErrorPixels),guardOrShaderInputs:0}));
