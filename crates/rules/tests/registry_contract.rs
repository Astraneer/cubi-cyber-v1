use std::collections::BTreeMap;

use core_types::{Cell, CellProperties, ChannelMask};
use rules::{blocks::*, ids::*, items::*};

fn donor_numeric_constants(source: &str, allowed_types: &[&str]) -> BTreeMap<String, u32> {
    source
        .lines()
        .filter_map(|line| {
            let declaration = line.strip_prefix("pub(crate) const ")?;
            let (name, rest) = declaration.split_once(':')?;
            let (ty, rest) = rest.split_once('=')?;
            if !allowed_types.contains(&ty.trim()) {
                return None;
            }
            let value = rest.split_once(';')?.0.trim().parse().ok()?;
            Some((name.to_owned(), value))
        })
        .collect()
}

#[test]
fn every_named_numeric_id_matches_the_pinned_donor() {
    let mut expected = donor_numeric_constants(
        include_str!("../../../donor/crates/voxel-core/src/registry/ids.rs"),
        &["BlockId", "u32"],
    );
    expected.extend(donor_numeric_constants(
        include_str!("../../../donor/crates/voxel-core/src/registry/items.rs"),
        &["ItemId"],
    ));
    let actual: BTreeMap<_, _> = rules::bindings::DONOR_NUMERIC_IDS
        .iter()
        .map(|&(name, value)| (name.to_owned(), value))
        .collect();
    assert_eq!(expected.len(), 265);
    assert_eq!(actual.len(), rules::bindings::DONOR_NUMERIC_IDS.len());
    assert_eq!(actual, expected);
}

