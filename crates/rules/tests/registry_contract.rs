#[test]
fn unknown_ids_are_explicit_and_never_become_air() {
    assert_eq!(rules::block_by_name("air").map(|(id, _)| id), Some(AIR));
    assert!(rules::block_by_name("not_a_block").is_none());
    assert!(rules::block_by_name("unknown").is_none());
    for id in [34, 39, 81, 99, 106, 109, 116, 255, 256, u16::MAX] {
        assert!(rules::block(id).is_none(), "reserved block {id}");
        let properties = rules::properties(Cell::from_parts(id, 0));
        assert!(properties.occupied && properties.opaque && properties.collidable);
        assert!(properties.blocks_projectile);
        assert_ne!(properties, CellProperties::AIR);
    }
    for id in [0, 34, 35, 99, 330, 339, 353, 399, 411, 419, 434, u16::MAX] {
        assert!(rules::item(id).is_none(), "reserved item {id}");
    }
    assert!(rules::item_by_name("not_an_item").is_none());
    assert_eq!(
        rules::item_by_name("iron_ingot").map(|(id, _)| id),
        Some(260)
    );
}

#[test]
fn air_fluids_cutout_and_partial_shapes_have_distinct_masks() {
    assert_eq!(rules::properties(Cell::AIR), CellProperties::AIR);
    let water = rules::properties(Cell::from_parts(WATER, 7));
    assert!(water.occupied && water.fluid);
    assert!(!water.opaque && !water.collidable && !water.blocks_projectile && !water.emitter());
    assert_eq!(water.light_opacity, 1);
    let lava = rules::properties(Cell::from_parts(LAVA, 0));
    assert!(lava.fluid && lava.emitter());
    assert_eq!(lava.emission, [15; 3]);
    assert!(!lava.collidable && !lava.opaque);
    let leaves = rules::properties(Cell::from_parts(LEAVES, 0));
    assert!(leaves.occupied && leaves.collidable && leaves.blocks_projectile);
    assert!(!leaves.opaque);
    assert_eq!(leaves.light_opacity, 1);
    let glass = rules::properties(Cell::from_parts(GLASS, 0));
    assert!(glass.collidable && glass.blocks_projectile);
    assert!(!glass.opaque);
    assert_eq!(glass.light_opacity, 0);
    let snow_one = rules::properties(Cell::from_parts(SNOW_LAYER, 0));
    let snow_eight = rules::properties(Cell::from_parts(SNOW_LAYER, 7));
    assert!(snow_one.occupied && snow_eight.occupied);
    assert!(!snow_one.collidable && snow_eight.collidable);
    assert_ne!(snow_one.shape, snow_eight.shape);
    assert_eq!(collision_of(cell(SNOW_LAYER, 7))[0].hi[1], 14.0 / 16.0);
    assert_eq!(collision_of(cell(FARMLAND, 0))[0].hi[1], 15.0 / 16.0);
}

fn cell(id: u16, state: u16) -> u32 {
    Cell::from_parts(id, state).raw()
}

#[test]
fn emission_only_state_changes_do_not_dirty_geometry() {
    for id in [FURNACE, REDSTONE_ORE, HEAT_GENERATOR, ENERGIZED_SMELTER] {
        let unlit = rules::properties(Cell::from_parts(id, 2));
        let lit = rules::properties(Cell::from_parts(id, 2 | ST_LIT));
        assert_eq!(unlit.shape, lit.shape, "geometry {id}");
        assert_eq!(unlit.emission, [0; 3]);
        assert!(lit.emitter());
        assert_eq!(unlit.changed_channels(lit), ChannelMask::EMISSION);
    }
    // Leaf decay/persistence affects simulation, not the geometry/material key.
    assert_eq!(
        rules::properties(Cell::from_parts(LEAVES, 0)).shape,
        rules::properties(Cell::from_parts(LEAVES, 3)).shape
    );
    assert_ne!(
        rules::properties(Cell::from_parts(LOG, 0)).shape,
        rules::properties(Cell::from_parts(LOG, 1)).shape
    );
}

#[test]
fn attachment_shapes_and_transmitter_state_preserve_the_donor_layout() {
    assert_eq!(outline_of(cell(LADDER, 3)), rules::shapes::LADDER_SHAPES[1]);
    assert_eq!(
        outline_of(cell(WALL_TORCH, 4)),
        rules::shapes::WALL_TORCH_SHAPES[2]
    );
    assert!(collision_of(cell(WALL_TORCH, 4)).is_empty());
    for mask in 0..64 {
        let packed = rules::arms::with_arms(0x8080, rules::arms::arms_from_mask(mask));
        assert_eq!(rules::arms::arm_mask(packed), mask);
        assert_eq!(packed & 0x8080, 0x8080);
        assert_eq!(
            outline_of(cell(UNIVERSAL_CABLE, packed)).len(),
            1 + mask.count_ones() as usize
        );
        assert_eq!(
            outline_of(cell(MECHANICAL_PIPE, packed)).len(),
            1 + mask.count_ones() as usize
        );
    }
}

fn break_ticks(item: u16, block: u16, grounded: bool, in_water: bool) -> u32 {
    let delta = break_delta(item, bdef(block), grounded, in_water);
    assert!(delta > 0.0);
    let mut progress = 0f32;
    let mut ticks = 0;
    while progress < 1.0 {
        progress += delta;
        ticks += 1;
    }
    ticks
}

#[test]
fn java_breaking_formula_preserves_f32_tick_counts() {
    for (id, ticks) in [
        (DIRT, 15),
        (GRASS, 18),
        (SAND, 15),
        (LEAVES, 6),
        (LOG, 61),
        (STONE, 151),
        (COBBLE, 201),
    ] {
        assert_eq!(break_ticks(0, id, true, false), ticks);
    }
    assert_eq!(break_ticks(I_WOODEN_PICKAXE, STONE, true, false), 23);
    assert_eq!(break_ticks(I_WOODEN_PICKAXE + 5, STONE, true, false), 12);
    assert_eq!(break_ticks(I_WOODEN_PICKAXE + 10, STONE, true, false), 8);
    assert_eq!(break_ticks(0, DIRT, false, true), 376);
    assert_eq!(break_delta(0, bdef(BEDROCK), true, false), 0.0);
    assert!(!can_harvest(0, bdef(STONE)));
    assert!(can_harvest(I_WOODEN_PICKAXE, bdef(STONE)));
    assert!(!can_harvest(I_WOODEN_PICKAXE, bdef(IRON_ORE)));
}

